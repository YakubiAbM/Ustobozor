def upsert_products(products: List[Dict], replace_category: bool = False) -> None:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        if replace_category:
            deleted = db.query(ProductDB).filter(ProductDB.category == CATEGORY).delete(synchronize_session=False)
            db.commit()
            print(f"🧹 Удалено из категории '{CATEGORY}': {deleted}")

        existing = db.query(ProductDB).filter(ProductDB.category == CATEGORY).all()
        key_to_product = {
            (p.name.strip().lower(), (p.brand or "").strip().lower(), p.category.strip().lower(), (p.subcategory or "").strip().lower()): p
            for p in existing
        }

        created = 0
        updated = 0
        for data in products:
            key = (
                data["name"].strip().lower(),
                data["brand"].strip().lower(),
                data["category"].strip().lower(),
                data["subcategory"].strip().lower(),
            )
            obj = key_to_product.get(key)
            if obj:
                obj.price = data["price"]
                obj.unit = data["unit"]
                obj.description = data["description"]
                obj.sales_count = data.get("sales_count", obj.sales_count or 0)
                updated += 1
            else:
                db.add(ProductDB(**data))
                created += 1

        db.commit()
        if refresh_products_cache:
            try:
                refresh_products_cache(db)
            except Exception:
                pass
        print(f"✅ Готово. Создано: {created}, обновлено: {updated}, всего в наборе: {len(products)}")
    finally:
        db.close()


def main():
    parser = argparse.ArgumentParser(description="Seed популярных товаров 'Кафель и плитка' для рынка Таджикистана.")
    parser.add_argument(
        "--replace-category",
        action="store_true",
        help="Удалить существующие товары категории 'Кафель и плитка' и загрузить набор заново.",
    )
    args = parser.parse_args()

    products = build_kafel_catalog()
    # Нормализация JSON-полей/артикула по умолчанию
    for i, item in enumerate(products, start=1):
        item["articul"] = item["articul"] or f"KF-{1000 + i}"
        item["photos_json"] = item.get("photos_json", "[]")
        item["sizes_json"] = item.get("sizes_json", "[]")
        item["colors_json"] = item.get("colors_json", "[]")

    print(f"📦 Подготовлено товаров: {len(products)}")
    upsert_products(products, replace_category=args.replace_category)


if __name__ == "__main__":
    main()

